    public ReportFrame(int reservationId) {
        this.reservationId = reservationId;
        initComponents();
        SidebarUtil.guard(this, Role.PATIENT);
        applyTheme();
        cmbReason.setModel(new DefaultComboBoxModel<ReportReason>(ReportReason.values()));
        cmbReason.setSelectedIndex(-1);
        load();
    }

    private void applyTheme() {
        UITheme.styleFrame(this);
        UITheme.styleHeading(lblTitle);
        UITheme.styleMuted(lblHint);
        UITheme.styleDangerButton(btnSend);
        txtDetails.setFont(UITheme.FONT_BODY);
    }

    private void load() {
        try {
            ReservationView v = new ReservationService().getView(reservationId);
            if (v == null) {
                lblAbout.setText("Reservation not found");
                btnSend.setEnabled(false);
                return;
            }
            lblAbout.setText("<html>Reservation <b>" + v.getReservation().getCode() + "</b> · " + v.getMedicineShort()
                    + " × " + v.getReservation().getQuantity() + "<br>at " + v.getPharmacyName() + "</html>");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Could not load the reservation:\n" + ErrorLog.describe(e), TITLE,
                    JOptionPane.ERROR_MESSAGE);
            btnSend.setEnabled(false);
        }
    }

    private void send() {
        if (cmbReason.getSelectedItem() == null) {
            fail("Choose what went wrong.", cmbReason);
            return;
        }
        String details = txtDetails.getText().trim();
        if (details.length() < ReportService.MIN_DETAILS) {
            fail("Describe the problem in a few words (at least " + ReportService.MIN_DETAILS + " characters).", txtDetails);
            return;
        }
        Integer me = Session.getUserId();
        if (me == null) {
            fail("Please log in again.", btnSend);
            return;
        }
        try {
            reportService.reportReservation(me, reservationId, (ReportReason) cmbReason.getSelectedItem(), details);
            JOptionPane.showMessageDialog(this, "Thank you. An admin will review your report.", TITLE,
                    JOptionPane.INFORMATION_MESSAGE);
            dispose();
        } catch (ServiceException e) {
            fail(e.getMessage(), ValidationUtil.isBlank(details) ? txtDetails : cmbReason);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Could not send the report:\n" + ErrorLog.describe(e), TITLE,
                    JOptionPane.ERROR_MESSAGE);
        }
    }

    private void fail(String message, JComponent field) {
        JOptionPane.showMessageDialog(this, message, TITLE, JOptionPane.WARNING_MESSAGE);
        SwingUtilities.invokeLater(field::requestFocusInWindow);
    }

