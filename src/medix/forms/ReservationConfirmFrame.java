    private void applyTheme() {
        UITheme.styleFrame(this);
        lblTitle.setFont(UITheme.FONT_TITLE);
        lblTitle.setForeground(UITheme.SUCCESS);
        UITheme.styleMuted(lblSubtitle);
        lblCode.setFont(new Font(UITheme.FONT_FAMILY, Font.BOLD, 30));
        lblCode.setForeground(UITheme.SIDEBAR);
        lblCode.setOpaque(true);
        lblCode.setBackground(UITheme.WHITE);
        lblCode.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createDashedBorder(UITheme.ACCENT, 2f, 6f, 4f, true),
                BorderFactory.createEmptyBorder(8, 12, 8, 12)));
        UITheme.styleMuted(lblHint);
        UITheme.stylePrimaryButton(btnGoToReservations);
        getRootPane().setDefaultButton(btnGoToReservations);
    }

    private void showReservation(ReservationView v) {
        Reservation r = v.getReservation();
        lblCode.setText(r.getCode());
        lblPharmacy.setText("<html><b>" + v.getMedicineShort() + " × " + r.getQuantity() + "</b> at "
                + v.getPharmacyName() + (v.getPharmacyPhone() == null ? "" : " · " + v.getPharmacyPhone()) + "</html>");
        lblHoldUntil.setText("<html>Held until <b>" + r.getExpiresAt().substring(11, 16) + "</b> on "
                + DateUtil.toDisplayDate(r.getExpiresAt()) + "</html>");
        lblAmount.setText(v.getAmount() == null ? "Amount: ask the pharmacy"
                : "<html>Amount: <b>" + String.format(Locale.US, "Tk %.2f", v.getAmount()) + "</b> (pay at the pharmacy)</html>");
        lblHint.setText(UITheme.wrapHtml("Call the pharmacy before you travel. "
                + "The hold ends automatically at the time above.", 340));
    }

