    private void applyTheme() {
        UITheme.styleFrame(this);
        UITheme.styleHeading(lblTitle);
        UITheme.styleMuted(lblInfo);
        lblInfo.setText(UITheme.wrapHtml("The new admin can verify pharmacies, handle reports and manage users.", 320));
        for (JLabel l : new JLabel[]{lblName, lblEmail, lblPhone, lblPassword, lblConfirm}) {
            l.setFont(UITheme.FONT_BODY_BOLD);
        }
        txtPhone.putClientProperty("JTextField.placeholderText", "01712345678");
        txtPassword.putClientProperty("JTextField.placeholderText", "At least " + ValidationUtil.MIN_PASSWORD_LENGTH
                + " characters");
        UITheme.stylePrimaryButton(btnCreate);
    }

    private void create() {
        String password = new String(txtPassword.getPassword());
        if (ValidationUtil.isBlank(txtName.getText())) {
            fail("Enter the admin's full name.", txtName);
            return;
        }
        if (!ValidationUtil.isValidEmail(txtEmail.getText())) {
            fail("Enter a valid email address.", txtEmail);
            return;
        }
        if (!ValidationUtil.isValidBdMobile(txtPhone.getText())) {
            fail("Enter a Bangladeshi mobile number like 01712345678.", txtPhone);
            return;
        }
        if (!ValidationUtil.isValidPassword(password)) {
            fail("The password must be at least " + ValidationUtil.MIN_PASSWORD_LENGTH + " characters.", txtPassword);
            return;
        }
        if (!password.equals(new String(txtConfirm.getPassword()))) {
            fail("The passwords do not match.", txtConfirm);
            return;
        }
        try {
            User admin = authService.registerAdmin(txtName.getText(), txtEmail.getText(), txtPhone.getText(), password);
            JOptionPane.showMessageDialog(this, admin.getFullName() + " can now log in as an admin with "
                    + admin.getEmail() + ".", TITLE, JOptionPane.INFORMATION_MESSAGE);
            if (onSaved != null) {
                onSaved.run();
            }
            dispose();
        } catch (AuthException e) {
            fail(e.getMessage(), e.getMessage().contains("email") ? txtEmail : txtName);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Could not create the account:\n" + ErrorLog.describe(e), TITLE,
                    JOptionPane.ERROR_MESSAGE);
        }
    }

    private void fail(String message, JComponent field) {
        JOptionPane.showMessageDialog(this, message, TITLE, JOptionPane.WARNING_MESSAGE);
        SwingUtilities.invokeLater(field::requestFocusInWindow);
    }

